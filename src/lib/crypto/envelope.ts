/**
 * Phase D2 / Programme 16 — tenant-aware envelope encryption abstraction
 * for the SaaS (productization) build.
 *
 * This module is a NEW, tenant-aware scheme. It does NOT decrypt or
 * migrate any existing ciphertext: existing tokens use
 * src/lib/crypto.ts's `iv:ct:tag` hex format under the unresolved
 * production key, and compatibility with that scheme is explicitly NOT
 * claimed. Nothing in this file reads that key, and nothing here can
 * open a legacy `iv:ct:tag` string (the test suite pins this).
 *
 * Model — envelope encryption with a two-level key hierarchy:
 *   - A master key (KEK, key-encrypting key) is supplied BY THE CALLER
 *     as 64 hex characters (32 bytes), the same shape as the existing
 *     scheme's key. This module NEVER reads the environment and has no
 *     default or fallback key: production must source the KEK from a
 *     real KMS/HSM (see saas/PHASE_16_ENCRYPTION_AND_STORAGE.md).
 *   - Each tenant has a random 32-byte data-encryption key (DEK),
 *     generated by `generateTenantDek()`. The DEK is wrapped (encrypted
 *     under the KEK) and the wrapped form travels inside every envelope,
 *     so no separate DEK store is needed for decryption.
 *   - Plaintext data is AES-256-GCM-encrypted under the DEK.
 *
 * Tenant binding — the tenantId is cryptographically bound TWICE:
 *   1. Stored-field check: `decryptForTenant` compares the envelope's
 *      stored tenantId against the caller's requested tenantId and
 *      throws 'tenant-mismatch' BEFORE any cryptographic operation.
 *   2. GCM AAD: the tenantId is the Additional Authenticated Data for
 *      BOTH the DEK wrap and the data encryption. An envelope whose
 *      stored tenantId field is edited to another tenant therefore
 *      fails GCM authentication even when the caller asks for the
 *      edited tenant — a transplanted envelope cannot be opened.
 *
 * Key versioning / rotation — every envelope carries a `keyId`
 * identifying the master key that wrapped its DEK. Decryption accepts
 * a keyring (Record<keyId, masterKeyHex>): rotation = encrypt new
 * envelopes under a new keyId while the keyring still holds the old
 * key, so old envelopes keep decrypting. An envelope whose keyId is
 * absent from the keyring fails with 'unknown-key-id'.
 *
 * Re-wrap (Programme 23) — `rewrapForTenant` migrates an existing
 * envelope to a new master key WITHOUT touching the data seal: the
 * DEK is unwrapped under the envelope's current KEK and re-wrapped
 * under the target KEK (fresh IV), so the data iv/ct/tag are carried
 * over byte-for-byte and the plaintext is never exposed to the
 * migration path. This is the rescue path for rotation rollback
 * (Programme 17 §6.5): envelopes stranded at 'unknown-key-id' after
 * their keyId leaves the ring can first be re-wrapped while the old
 * key is still available. The TARGET keyId of a re-wrap must follow
 * the governed keyId format (`isGovernedKeyId`, Programme 17 §5
 * issuance governance); the encrypt/decrypt paths deliberately keep
 * their historical permissive, exact-match keyId semantics so every
 * previously issued envelope remains usable verbatim.
 *
 * Public API contract (summary; full contract:
 * saas/PHASE_24_KEY_ROTATION_LIFECYCLE_SPEC.md, Part B) — all three
 * operations are synchronous, take a single options object, and either
 * return a fresh string (encrypt/re-wrap) or the plaintext string
 * (decrypt) or throw a typed `EnvelopeError`; no partial output exists.
 * Master keys are caller-supplied 64-hex-character strings (exactly 32
 * bytes; `masterKeyFromHex` is the single validation point for every
 * path). Guarantee boundary (Programme 24, B3): rewrapForTenant
 * authenticates and re-protects the wrapped DEK; it does not validate
 * the integrity of the underlying encrypted payload — a tampered data
 * seal re-wraps successfully and fails later, at decrypt.
 *
 * Envelope format — a single string:
 *   env1.<base64url(JSON)>
 * where the JSON is:
 *   { v: 1, tenantId, keyId,
 *     wrappedDek: { iv, ct, tag },   // hex; DEK wrapped under the KEK
 *     iv, ct, tag }                  // hex; data encrypted under the DEK
 *
 * Serialized-form hardening (Programme 25, closing ChatGPT Iteration-2
 * findings F25-A/F25-B/F25-C): the parser accepts ONLY the canonical
 * form this module produces — the component after `env1.` must be
 * unpadded base64url over the exact alphabet `[A-Za-z0-9_-]`, must
 * re-encode byte-for-byte to itself (no non-canonical trailing bits),
 * and every IV must be exactly 12 bytes (24 hex chars) and every auth
 * tag exactly 16 bytes (32 hex chars), for both seals. Anything else is
 * `malformed-envelope`, rejected before any key lookup or GCM work
 * (Programme 24 had documented the decoder's whitespace/padding
 * leniency as observation O-1; the expanded finding — the decoder also
 * ignores EMBEDDED invalid characters — closed it as a defect).
 * Keyring lookup is by OWN property only: a keyId naming an inherited
 * Object property (`constructor`, `toString`, …) is absent unless the
 * keyring itself defines it, so it fails `unknown-key-id` as the
 * contract requires. Encrypt/decrypt semantics for valid inputs are
 * unchanged (the encryptor has always emitted exactly this form).
 *
 * Runs on the Node runtime and on Cloudflare Workers via the
 * `nodejs_compat` flag, exactly like src/lib/crypto.ts.
 */

import { createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';

const ALGORITHM = 'aes-256-gcm';
const IV_LENGTH = 12; // 96-bit IV — recommended for GCM
const AUTH_TAG_LENGTH = 16;
const DEK_LENGTH = 32; // 256-bit data-encryption key
const ENVELOPE_PREFIX = 'env1.';
// Programme 25 (WS2): the serialized format fixes the IV and tag sizes
// (the encryptor always emits exactly these); the parser enforces them.
const IV_HEX_LENGTH = IV_LENGTH * 2; // 24 hex chars
const TAG_HEX_LENGTH = AUTH_TAG_LENGTH * 2; // 32 hex chars
// Programme 25 (WS1): canonical unpadded base64url alphabet — the only
// characters permitted in the component after the prefix.
const BASE64URL_BODY_PATTERN = /^[A-Za-z0-9_-]+$/;

export type EnvelopeErrorCode =
  | 'malformed-envelope'
  | 'unknown-key-id'
  | 'tenant-mismatch'
  | 'decrypt-failed';

/** Typed failure for every envelope operation. `code` is stable for callers to branch on. */
export class EnvelopeError extends Error {
  readonly code: EnvelopeErrorCode;

  constructor(code: EnvelopeErrorCode, message: string) {
    super(message);
    this.name = 'EnvelopeError';
    this.code = code;
  }
}

interface GcmSealed {
  iv: string; // hex
  ct: string; // hex
  tag: string; // hex
}

interface EnvelopePayload {
  v: 1;
  tenantId: string;
  keyId: string;
  wrappedDek: GcmSealed;
  iv: string;
  ct: string;
  tag: string;
}

function masterKeyFromHex(masterKeyHex: string): Buffer {
  // Same strict validation as src/lib/crypto.ts: validate the string
  // itself, not just the decoded length (Buffer.from(_, 'hex') silently
  // stops at the first non-hex pair). A malformed master key is a
  // decryption failure, never a silent fallback.
  if (typeof masterKeyHex !== 'string' || !/^[0-9a-fA-F]{64}$/.test(masterKeyHex)) {
    throw new EnvelopeError(
      'decrypt-failed',
      'Master key must be exactly 32 bytes (64 hex characters).',
    );
  }
  return Buffer.from(masterKeyHex, 'hex');
}

function gcmEncrypt(key: Buffer, plaintext: Buffer, aad: string): GcmSealed {
  const iv = randomBytes(IV_LENGTH);
  const cipher = createCipheriv(ALGORITHM, key, iv, { authTagLength: AUTH_TAG_LENGTH });
  cipher.setAAD(Buffer.from(aad, 'utf8'));
  const ct = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  return { iv: iv.toString('hex'), ct: ct.toString('hex'), tag: cipher.getAuthTag().toString('hex') };
}

function gcmDecrypt(key: Buffer, sealed: GcmSealed, aad: string): Buffer {
  const decipher = createDecipheriv(ALGORITHM, key, Buffer.from(sealed.iv, 'hex'), {
    authTagLength: AUTH_TAG_LENGTH,
  });
  decipher.setAAD(Buffer.from(aad, 'utf8'));
  decipher.setAuthTag(Buffer.from(sealed.tag, 'hex'));
  return Buffer.concat([decipher.update(Buffer.from(sealed.ct, 'hex')), decipher.final()]);
}

function isHexString(value: unknown): value is string {
  return typeof value === 'string' && value.length > 0 && value.length % 2 === 0 && /^[0-9a-fA-F]+$/.test(value);
}

/** Hex string of exactly `hexLength` characters (Programme 25 WS2 format enforcement). */
function isHexStringOfLength(value: unknown, hexLength: number): value is string {
  return typeof value === 'string' && value.length === hexLength && /^[0-9a-fA-F]+$/.test(value);
}

/** Data ciphertext only: an empty plaintext encrypts to an empty ct, so '' is valid here. */
function isHexStringOrEmpty(value: unknown): value is string {
  return typeof value === 'string' && value.length % 2 === 0 && /^[0-9a-fA-F]*$/.test(value);
}

function isGcmSealed(value: unknown): value is GcmSealed {
  if (typeof value !== 'object' || value === null) return false;
  const sealed = value as Record<string, unknown>;
  // IV and tag sizes are fixed by the format (Programme 25 WS2); the
  // wrapped ciphertext length is variable (it wraps a fixed-size DEK
  // today, but length is not part of the seal's structural contract).
  return (
    isHexStringOfLength(sealed['iv'], IV_HEX_LENGTH) &&
    isHexString(sealed['ct']) &&
    isHexStringOfLength(sealed['tag'], TAG_HEX_LENGTH)
  );
}

function parseEnvelope(envelope: string): EnvelopePayload {
  if (typeof envelope !== 'string' || !envelope.startsWith(ENVELOPE_PREFIX)) {
    throw new EnvelopeError('malformed-envelope', 'Envelope must be a string starting with "env1.".');
  }
  const body = envelope.slice(ENVELOPE_PREFIX.length);
  // Programme 25 (WS1, closes observation O-1): strict lexical
  // validation BEFORE decoding. Node's base64url decoder is lenient —
  // it ignores whitespace, tolerates trailing padding, and silently
  // drops even EMBEDDED characters outside the alphabet, so several
  // distinct strings decoded to the same payload (multiple serialized
  // forms per envelope: hash/dedup inconsistency, cross-implementation
  // divergence). The serialized contract is the canonical form this
  // module itself produces: unpadded base64url over [A-Za-z0-9_-]
  // only, and a decode → re-encode round-trip must reproduce the input
  // byte-for-byte (this also rejects non-canonical trailing-bit forms
  // the alphabet check alone cannot see). No self-produced envelope can
  // fail this: the encoder emits canonical unpadded base64url by
  // construction (pinned by tests).
  if (!BASE64URL_BODY_PATTERN.test(body) || Buffer.from(body, 'base64url').toString('base64url') !== body) {
    throw new EnvelopeError('malformed-envelope', 'Envelope payload is not canonical unpadded base64url.');
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(Buffer.from(body, 'base64url').toString('utf8'));
  } catch {
    throw new EnvelopeError('malformed-envelope', 'Envelope payload is not valid base64url-encoded JSON.');
  }
  if (typeof parsed !== 'object' || parsed === null) {
    throw new EnvelopeError('malformed-envelope', 'Envelope payload is not a JSON object.');
  }
  const payload = parsed as Record<string, unknown>;
  if (
    payload['v'] !== 1 ||
    typeof payload['tenantId'] !== 'string' ||
    (payload['tenantId'] as string).length === 0 ||
    typeof payload['keyId'] !== 'string' ||
    (payload['keyId'] as string).length === 0 ||
    !isGcmSealed(payload['wrappedDek']) ||
    !isHexStringOfLength(payload['iv'], IV_HEX_LENGTH) ||
    !isHexStringOrEmpty(payload['ct']) ||
    !isHexStringOfLength(payload['tag'], TAG_HEX_LENGTH)
  ) {
    throw new EnvelopeError('malformed-envelope', 'Envelope payload is missing or has invalid fields.');
  }
  return payload as unknown as EnvelopePayload;
}

/**
 * Keyring lookup by OWN property only (Programme 25 WS3, closes the
 * F25-C error-contract defect). Plain indexing resolves INHERITED
 * properties, so a keyId like 'constructor' or 'toString' — both valid
 * governed keyIds — "found" a value in an empty keyring and failed
 * later with 'decrypt-failed' instead of the contracted
 * 'unknown-key-id'. `Object.hasOwn` keeps absence honest while leaving
 * a keyring that genuinely defines such a keyId fully usable. An own
 * property explicitly set to `undefined` is still "absent" (the
 * caller compares against `undefined`), preserving prior semantics.
 */
function keyringLookup(keyring: Record<string, string>, keyId: string): string | undefined {
  return Object.hasOwn(keyring, keyId) ? keyring[keyId] : undefined;
}

/** Generate a fresh random per-tenant data-encryption key (32 bytes). */
export function generateTenantDek(): Buffer {
  return randomBytes(DEK_LENGTH);
}

/**
 * Governed keyId format (Programme 23; Programme 17 §5 issuance
 * governance): 1–64 characters, starting with an ASCII letter or digit,
 * followed by ASCII letters, digits, '.', '_' or '-'. Registry-issued
 * keyIds should satisfy this predicate; it is enforced for the target
 * of `rewrapForTenant`. It is intentionally NOT enforced by
 * `encryptForTenant` / `decryptForTenant`, whose exact-match,
 * verbatim keyId semantics are a pinned historical contract
 * (Programme 17 assurance §6.3) — tightening them is a separate,
 * explicitly approved breaking change.
 */
export const KEY_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/;

/** True when `keyId` satisfies the governed keyId format (see KEY_ID_PATTERN). */
export function isGovernedKeyId(keyId: string): boolean {
  return typeof keyId === 'string' && KEY_ID_PATTERN.test(keyId);
}

export interface EncryptForTenantOptions {
  /** Master key (KEK): exactly 64 hex characters, supplied by the caller. */
  masterKeyHex: string;
  /** Identifier of the master key; recorded in the envelope for keyring lookup at decrypt time. */
  keyId: string;
  /** Tenant the data belongs to; bound into the envelope as stored field AND GCM AAD. */
  tenantId: string;
  plaintext: string;
  /**
   * The tenant's DEK. Omit to generate a fresh one (the usual case for a
   * newly provisioned tenant); pass the tenant's existing DEK to encrypt
   * further values under the same tenant key. Either way the DEK is
   * wrapped under the master key inside the returned envelope.
   */
  dek?: Buffer;
}

/** Encrypt `plaintext` for `tenantId` and return the `env1.` envelope string. */
export function encryptForTenant(options: EncryptForTenantOptions): string {
  const { masterKeyHex, keyId, tenantId, plaintext } = options;
  if (typeof tenantId !== 'string' || tenantId.length === 0) {
    throw new EnvelopeError('malformed-envelope', 'A tenantId is required to encrypt.');
  }
  if (typeof keyId !== 'string' || keyId.length === 0) {
    throw new EnvelopeError('malformed-envelope', 'A keyId is required to encrypt.');
  }
  // Programme 24 (WS2-7): plaintext is validated like every other field —
  // a non-string previously fell through to an untyped TypeError from
  // Buffer.from, breaking this module's typed-EnvelopeError contract.
  if (typeof plaintext !== 'string') {
    throw new EnvelopeError('malformed-envelope', 'Plaintext must be a string to encrypt.');
  }
  const dek = options.dek ?? generateTenantDek();
  if (!Buffer.isBuffer(dek) || dek.length !== DEK_LENGTH) {
    throw new EnvelopeError('malformed-envelope', 'DEK must be a 32-byte Buffer (see generateTenantDek).');
  }
  const masterKey = masterKeyFromHex(masterKeyHex);
  const wrappedDek = gcmEncrypt(masterKey, dek, tenantId);
  const data = gcmEncrypt(dek, Buffer.from(plaintext, 'utf8'), tenantId);
  const payload: EnvelopePayload = {
    v: 1,
    tenantId,
    keyId,
    wrappedDek,
    iv: data.iv,
    ct: data.ct,
    tag: data.tag,
  };
  return ENVELOPE_PREFIX + Buffer.from(JSON.stringify(payload), 'utf8').toString('base64url');
}

export interface DecryptForTenantOptions {
  /** Master keys by keyId. Rotation keeps old keyIds present so old envelopes still decrypt. */
  keyring: Record<string, string>;
  /** The tenant the caller expects this envelope to belong to. */
  tenantId: string;
  envelope: string;
}

/**
 * Decrypt an `env1.` envelope for `tenantId`.
 *
 * @throws {EnvelopeError} 'malformed-envelope' — not an env1 envelope / bad payload shape
 * @throws {EnvelopeError} 'tenant-mismatch' — stored tenantId ≠ requested tenantId (pre-crypto check)
 * @throws {EnvelopeError} 'unknown-key-id' — the envelope's keyId is absent from the keyring
 * @throws {EnvelopeError} 'decrypt-failed' — GCM authentication failed (wrong key, tampered
 *   wrapped DEK / ciphertext / tag, or tenantId edited inside the envelope: the AAD binding)
 */
export function decryptForTenant(options: DecryptForTenantOptions): string {
  const payload = parseEnvelope(options.envelope);

  // Tenant check FIRST, before any crypto and before key lookup: a caller
  // asking for the wrong tenant learns nothing about keys or validity.
  if (payload.tenantId !== options.tenantId) {
    throw new EnvelopeError(
      'tenant-mismatch',
      'Envelope belongs to a different tenant than the one requested.',
    );
  }

  const masterKeyHex = keyringLookup(options.keyring, payload.keyId);
  if (masterKeyHex === undefined) {
    throw new EnvelopeError('unknown-key-id', `No master key in the keyring for keyId '${payload.keyId}'.`);
  }
  const masterKey = masterKeyFromHex(masterKeyHex);

  try {
    const dek = gcmDecrypt(masterKey, payload.wrappedDek, options.tenantId);
    if (dek.length !== DEK_LENGTH) {
      throw new Error('unwrapped DEK has an unexpected length');
    }
    const plaintext = gcmDecrypt(
      dek,
      { iv: payload.iv, ct: payload.ct, tag: payload.tag },
      options.tenantId,
    );
    return plaintext.toString('utf8');
  } catch (err) {
    if (err instanceof EnvelopeError) throw err;
    throw new EnvelopeError(
      'decrypt-failed',
      'Envelope decryption failed (wrong key or tampered envelope).',
    );
  }
}

export interface RewrapForTenantOptions {
  /** The envelope to migrate. It is never modified; a new envelope string is returned. */
  envelope: string;
  /** The tenant the caller expects this envelope to belong to. */
  tenantId: string;
  /** Master keys by keyId, used to unwrap the DEK under the envelope's CURRENT keyId. */
  keyring: Record<string, string>;
  /** Governed-format identifier of the target master key (see isGovernedKeyId). */
  newKeyId: string;
  /** Target master key (KEK): exactly 64 hex characters, supplied by the caller. */
  newMasterKeyHex: string;
}

/**
 * Re-wrap an `env1.` envelope's DEK under a new master key
 * (Programme 23), returning a NEW envelope string. The data seal
 * (iv/ct/tag) is carried over byte-for-byte — the plaintext is never
 * decrypted on this path — and the wrapped DEK is re-sealed with a
 * fresh IV under the target KEK, with the tenantId again bound as
 * GCM AAD. After a re-wrap, the envelope decrypts under a keyring
 * that holds ONLY the target keyId, so the old keyId can be retired
 * without stranding it.
 *
 * Check order (pinned by tests): malformed envelope → tenant
 * pre-check ('tenant-mismatch', before any key or format logic) →
 * target keyId governance ('malformed-envelope') → current keyId
 * lookup ('unknown-key-id') → DEK unwrap ('decrypt-failed').
 *
 * @throws {EnvelopeError} 'malformed-envelope' — bad envelope shape, or the target keyId
 *   does not follow the governed format
 * @throws {EnvelopeError} 'tenant-mismatch' — stored tenantId ≠ requested tenantId
 * @throws {EnvelopeError} 'unknown-key-id' — the envelope's CURRENT keyId is absent from the keyring
 * @throws {EnvelopeError} 'decrypt-failed' — DEK unwrap failed (wrong current key / tampered
 *   wrapped DEK), or the target master key is malformed
 */
export function rewrapForTenant(options: RewrapForTenantOptions): string {
  const payload = parseEnvelope(options.envelope);

  // Tenant check FIRST, exactly as in decryptForTenant: a caller asking
  // for the wrong tenant learns nothing about keys, formats or validity.
  if (payload.tenantId !== options.tenantId) {
    throw new EnvelopeError(
      'tenant-mismatch',
      'Envelope belongs to a different tenant than the one requested.',
    );
  }

  // The target keyId is a NEW issuance, so the governed format applies.
  // The message deliberately does not echo the supplied value (it is
  // untrusted caller input; cf. Programme 17 §6.10 log hygiene).
  if (!isGovernedKeyId(options.newKeyId)) {
    throw new EnvelopeError(
      'malformed-envelope',
      'Target keyId does not follow the governed keyId format.',
    );
  }

  const currentMasterKeyHex = keyringLookup(options.keyring, payload.keyId);
  if (currentMasterKeyHex === undefined) {
    throw new EnvelopeError('unknown-key-id', `No master key in the keyring for keyId '${payload.keyId}'.`);
  }
  const currentMasterKey = masterKeyFromHex(currentMasterKeyHex);

  let dek: Buffer;
  try {
    dek = gcmDecrypt(currentMasterKey, payload.wrappedDek, options.tenantId);
    if (dek.length !== DEK_LENGTH) {
      throw new Error('unwrapped DEK has an unexpected length');
    }
  } catch (err) {
    if (err instanceof EnvelopeError) throw err;
    throw new EnvelopeError(
      'decrypt-failed',
      'Envelope re-wrap failed (wrong current key or tampered envelope).',
    );
  }

  const newMasterKey = masterKeyFromHex(options.newMasterKeyHex);
  const wrappedDek = gcmEncrypt(newMasterKey, dek, options.tenantId);
  const rewrapped: EnvelopePayload = {
    v: 1,
    tenantId: payload.tenantId,
    keyId: options.newKeyId,
    wrappedDek,
    iv: payload.iv,
    ct: payload.ct,
    tag: payload.tag,
  };
  return ENVELOPE_PREFIX + Buffer.from(JSON.stringify(rewrapped), 'utf8').toString('base64url');
}
