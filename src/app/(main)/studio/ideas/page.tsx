"use client";

/**
 * Creator Studio — Next Video Ideas (Programme S1).
 *
 * The built-in engine generates ideas instantly and offline. When the
 * instance has the free AI tier configured, "Enhance with Free AI"
 * swaps in model-generated ideas — always labelled by engine, and any
 * degradation (not configured, quota, unavailable) is shown as a plain
 * note while the built-in list stays on screen.
 */

import { useMemo, useState } from "react";
import { useRouter } from "next/navigation";
import { Lightbulb, Sparkles, BookmarkPlus, Check, Loader2, PenLine } from "lucide-react";
import { generateIdeas, IDEA_MODE_LABELS } from "@/lib/studio/ideaEngine";
import { getBrowserHandoffStore } from "@/lib/studio/handoff";
import { requestAiIdeas, type AiIdeasOutcome } from "@/lib/studio/aiClient";
import {
  STUDIO_CATEGORIES,
  type IdeaItem,
  type IdeaMode,
  type StudioCategory,
} from "@/lib/studio/types";
import {
  getBrowserProjectStore,
  STUDIO_PROJECTS_SAVE_FAILED_MESSAGE,
} from "@/lib/studio/projects";
import {
  EngineBadge,
  StudioToolHeader,
  studioCardClass,
  studioInputClass,
  studioLabelClass,
  studioPrimaryButtonClass,
} from "@/components/studio/ui";
import { cn } from "@/lib/utils";

const MODES = Object.keys(IDEA_MODE_LABELS) as IdeaMode[];

const AI_NOTES: Partial<Record<AiIdeasOutcome["status"], string>> = {
  not_configured:
    "Free AI is not configured on this instance, so you are seeing the built-in engine's ideas.",
  quota_reached:
    "Today's shared free AI quota is used up. The built-in engine's ideas are shown instead — they keep working.",
  daily_quota_reached:
    "You have reached today's per-user free AI limit. The built-in engine's ideas are shown instead.",
  rate_limited: "Too many free AI requests in a minute — wait a moment and try again.",
  ai_unavailable: "Free AI did not respond just now. The built-in engine's ideas are shown instead.",
  signed_out: "Sign in again to use the free AI enhancement — the built-in ideas work either way.",
};

export default function VideoIdeasPage() {
  const router = useRouter();
  const [topic, setTopic] = useState("");
  const [category, setCategory] = useState<StudioCategory>("Tech & AI Tools");
  const [mode, setMode] = useState<IdeaMode>("proven");
  const [aiIdeas, setAiIdeas] = useState<IdeaItem[] | null>(null);
  const [aiNote, setAiNote] = useState<string | null>(null);
  const [aiBusy, setAiBusy] = useState(false);
  const [savedIds, setSavedIds] = useState<Set<string>>(new Set());
  const [saveError, setSaveError] = useState<string | null>(null);

  const offlineIdeas = useMemo(
    () => (topic.trim() ? generateIdeas({ topic, category, mode, count: 8 }) : []),
    [topic, category, mode]
  );
  const ideas = aiIdeas ?? offlineIdeas;
  const engine = aiIdeas ? "free-ai" : "built-in";

  const enhance = async () => {
    if (!topic.trim()) return;
    setAiBusy(true);
    setAiNote(null);
    const outcome = await requestAiIdeas({ topic, category, mode, count: 8 });
    setAiBusy(false);
    if (outcome.status === "ok") {
      setAiIdeas(outcome.ideas);
      setAiNote(
        outcome.cached
          ? "Free AI result (cached — an identical request was already answered today)."
          : "Ideas generated by a free AI model for this topic."
      );
    } else {
      setAiIdeas(null);
      setAiNote(AI_NOTES[outcome.status] ?? null);
    }
  };

  const saveIdea = (idea: IdeaItem) => {
    try {
      getBrowserProjectStore().save({
        kind: "ideas",
        title: idea.title,
        summary: `${idea.format} · ${IDEA_MODE_LABELS[idea.mode]} · via ${idea.engine === "free-ai" ? "Free AI" : "built-in engine"}`,
        payload: { topic, category, ideas: [idea] },
      });
      setSavedIds((prev) => new Set(prev).add(idea.title));
      setSaveError(null);
    } catch {
      // Not saved: the idea stays unmarked so Save can be retried.
      setSaveError(STUDIO_PROJECTS_SAVE_FAILED_MESSAGE);
    }
  };

  const writeScript = (idea: IdeaItem) => {
    getBrowserHandoffStore().setScript({ topic: idea.title, from: "Next Video Ideas" });
    router.push("/studio/script");
  };

  return (
    <div className="space-y-5">
      <StudioToolHeader
        icon={Lightbulb}
        title="Next Video Ideas"
        purpose="Generate video ideas in proven formats, audience questions and trending angles."
        points={[
          "Three idea styles — proven formats, audience questions, trending angles",
          "Optional Free AI enhancement, always labelled by engine",
          "Save ideas to Projects, or write the script in one click",
        ]}
      />
      <div className={studioCardClass}>
        <p className="text-[13px] text-muted-foreground">
          Pick a topic and a style. The built-in engine answers instantly; free AI can
          enhance the list when it is configured on this instance.
        </p>
        <div className="mt-4 grid gap-3 sm:grid-cols-[1fr_220px] sm:items-end">
          <div>
            <label className={studioLabelClass} htmlFor="ideas-topic">Topic or niche</label>
            <input
              id="ideas-topic"
              className={studioInputClass}
              placeholder="e.g. home workouts for busy parents"
              value={topic}
              onChange={(e) => {
                setTopic(e.target.value);
                setAiIdeas(null);
              }}
              maxLength={120}
            />
          </div>
          <div>
            <label className={studioLabelClass} htmlFor="ideas-category">Category</label>
            <select
              id="ideas-category"
              className={studioInputClass}
              value={category}
              onChange={(e) => {
                setCategory(e.target.value as StudioCategory);
                setAiIdeas(null);
              }}
            >
              {STUDIO_CATEGORIES.map((c) => (
                <option key={c} value={c}>{c}</option>
              ))}
            </select>
          </div>
        </div>
        <div className="mt-3 flex flex-wrap items-center gap-2">
          {MODES.map((m) => (
            <button
              key={m}
              type="button"
              onClick={() => {
                setMode(m);
                setAiIdeas(null);
              }}
              className={cn(
                "rounded-full border px-3 py-1.5 text-xs transition-colors",
                mode === m
                  ? "border-primary/50 bg-primary/10 font-medium text-foreground"
                  : "border-border text-muted-foreground hover:text-foreground hover:bg-muted/60"
              )}
            >
              {IDEA_MODE_LABELS[m]}
            </button>
          ))}
          <span className="flex-1" />
          <button
            type="button"
            className={studioPrimaryButtonClass}
            onClick={enhance}
            disabled={!topic.trim() || aiBusy}
          >
            {aiBusy ? <Loader2 className="w-4 h-4 animate-spin" /> : <Sparkles className="w-4 h-4" />}
            Enhance with Free AI
          </button>
        </div>
        {aiNote && <p className="mt-3 text-xs text-muted-foreground">{aiNote}</p>}
        {saveError && (
          <p role="alert" className="mt-3 text-xs text-red-500">
            {saveError}
          </p>
        )}
      </div>

      {topic.trim() && (
        <div>
          <div className="mb-3 flex items-center gap-2">
            <h3 className="text-sm font-medium">
              {IDEA_MODE_LABELS[mode]} — for “{topic.trim()}”
            </h3>
            <EngineBadge engine={engine} />
          </div>
          <ul className="grid gap-3 sm:grid-cols-2">
            {ideas.map((idea) => (
              <li key={idea.title} className={cn(studioCardClass, "flex flex-col")}>
                <div className="flex items-start justify-between gap-2">
                  <span className="rounded-full bg-muted px-2 py-0.5 text-[11px] font-medium text-muted-foreground">
                    {idea.format}
                  </span>
                  <button
                    type="button"
                    onClick={() => saveIdea(idea)}
                    disabled={savedIds.has(idea.title)}
                    className="inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground disabled:opacity-60 transition-colors"
                    title="Save this idea to Projects"
                  >
                    {savedIds.has(idea.title) ? (
                      <Check className="w-3.5 h-3.5" />
                    ) : (
                      <BookmarkPlus className="w-3.5 h-3.5" />
                    )}
                    {savedIds.has(idea.title) ? "Saved" : "Save"}
                  </button>
                </div>
                <p className="mt-2 text-sm font-medium leading-snug">{idea.title}</p>
                <p className="mt-1 flex-1 text-[13px] text-muted-foreground leading-relaxed">{idea.whyItWorks}</p>
                <button
                  type="button"
                  onClick={() => writeScript(idea)}
                  className="mt-3 inline-flex items-center gap-1 self-start text-xs font-medium text-primary hover:underline"
                  title="Open this idea in the Script Builder"
                >
                  <PenLine className="w-3.5 h-3.5" /> Write the script
                </button>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}
